package it.unibo.gridgames.model.game2048;

/**
 * The four directions in which the tiles of a 2048 board can slide.
 */
public enum Direction {
    /** Tiles slide towards the top row. */
    UP,
    /** Tiles slide towards the bottom row. */
    DOWN,
    /** Tiles slide towards the leftmost column. */
    LEFT,
    /** Tiles slide towards the rightmost column. */
    RIGHT
}
